CREATE TABLE example (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL
);

CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(320), name VARCHAR(100), role VARCHAR(20) NOT NULL, status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL, updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'STAFF', 'ADMIN')),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE social_account (
    social_account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id), provider VARCHAR(30) NOT NULL,
    provider_user_id VARCHAR(255) NOT NULL, email VARCHAR(320),
    created_at TIMESTAMP(6) NOT NULL, updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_social_account_provider_user UNIQUE (provider, provider_user_id)
);

CREATE TABLE auth_session (
    auth_session_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id), refresh_token_hash VARCHAR(255) NOT NULL,
    device_id VARCHAR(255), device_name VARCHAR(255), expires_at TIMESTAMP(6) NOT NULL,
    revoked_at TIMESTAMP(6), last_used_at TIMESTAMP(6), created_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_auth_session_refresh_token_hash UNIQUE (refresh_token_hash)
);

CREATE TABLE store (
    store_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, public_id UUID NOT NULL,
    name VARCHAR(255) NOT NULL, description TEXT, location VARCHAR(500), banner_img_url VARCHAR(2048),
    status VARCHAR(20) NOT NULL, created_at TIMESTAMP(6) NOT NULL, updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_store_public_id UNIQUE (public_id),
    CONSTRAINT ck_store_status CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE event (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id BIGINT NOT NULL REFERENCES store(store_id), public_id UUID NOT NULL,
    title VARCHAR(255) NOT NULL, description TEXT, reservation_open_at TIMESTAMP(6) NOT NULL,
    reservation_close_at TIMESTAMP(6) NOT NULL, start_date DATE NOT NULL, end_date DATE NOT NULL,
    status VARCHAR(30) NOT NULL, max_party_size INT NOT NULL, hold_minutes INT NOT NULL,
    cancellation_deadline_minutes INT, check_in_open_minutes INT, check_in_close_minutes INT,
    created_at TIMESTAMP(6) NOT NULL, updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_event_public_id UNIQUE (public_id),
    CONSTRAINT ck_event_status CHECK (status IN ('DRAFT','SCHEDULED','RESERVATION_OPEN','RESERVATION_CLOSED','IN_PROGRESS','ENDED','CANCELED')),
    CONSTRAINT ck_event_reservation_window CHECK (reservation_open_at < reservation_close_at),
    CONSTRAINT ck_event_dates CHECK (start_date <= end_date),
    CONSTRAINT ck_event_max_party_size CHECK (max_party_size > 0),
    CONSTRAINT ck_event_hold_minutes CHECK (hold_minutes > 0)
);

CREATE TABLE time_slot (
    time_slot_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES event(event_id), public_id UUID NOT NULL,
    date DATE NOT NULL, start_time TIME NOT NULL, end_time TIME NOT NULL,
    capacity INT NOT NULL, reserved_count INT NOT NULL DEFAULT 0, status VARCHAR(20) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0, created_at TIMESTAMP(6) NOT NULL, updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_time_slot_public_id UNIQUE (public_id),
    CONSTRAINT uk_time_slot_schedule UNIQUE (event_id, date, start_time, end_time),
    CONSTRAINT ck_time_slot_status CHECK (status IN ('OPEN', 'CLOSED', 'CANCELED')),
    CONSTRAINT ck_time_slot_time CHECK (start_time < end_time),
    CONSTRAINT ck_time_slot_capacity CHECK (capacity > 0),
    CONSTRAINT ck_time_slot_reserved_count CHECK (reserved_count >= 0 AND reserved_count <= capacity)
);

CREATE TABLE reservation (
    reservation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id), time_slot_id BIGINT NOT NULL REFERENCES time_slot(time_slot_id),
    public_id UUID NOT NULL, reservation_number VARCHAR(50) NOT NULL, party_size INT NOT NULL,
    status VARCHAR(20) NOT NULL, idempotency_key VARCHAR(255), hold_expires_at TIMESTAMP(6),
    confirmed_at TIMESTAMP(6), canceled_at TIMESTAMP(6), checked_in_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL, updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_reservation_public_id UNIQUE (public_id),
    CONSTRAINT uk_reservation_number UNIQUE (reservation_number),
    CONSTRAINT uk_reservation_user_idempotency UNIQUE (user_id, idempotency_key),
    CONSTRAINT ck_reservation_party_size CHECK (party_size > 0),
    CONSTRAINT ck_reservation_status CHECK (status IN ('PENDING','CONFIRMED','CHECKED_IN','CANCELED','EXPIRED','NO_SHOW'))
);

CREATE TABLE waitlist (
    waitlist_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id), time_slot_id BIGINT NOT NULL REFERENCES time_slot(time_slot_id),
    public_id UUID NOT NULL, party_size INT NOT NULL, status VARCHAR(20) NOT NULL,
    offered_at TIMESTAMP(6), offer_expires_at TIMESTAMP(6), accepted_at TIMESTAMP(6), canceled_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL, updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_waitlist_public_id UNIQUE (public_id),
    CONSTRAINT ck_waitlist_party_size CHECK (party_size > 0),
    CONSTRAINT ck_waitlist_status CHECK (status IN ('WAITING','OFFERED','ACCEPTED','EXPIRED','CANCELED'))
);

CREATE UNIQUE INDEX uk_waitlist_active_user_slot ON waitlist(user_id, time_slot_id)
WHERE status IN ('WAITING', 'OFFERED');

CREATE TABLE qr_ticket (
    qr_ticket_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT NOT NULL REFERENCES reservation(reservation_id), token_hash VARCHAR(255) NOT NULL,
    issued_at TIMESTAMP(6) NOT NULL, expires_at TIMESTAMP(6), revoked_at TIMESTAMP(6), created_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_qr_ticket_reservation UNIQUE (reservation_id),
    CONSTRAINT uk_qr_ticket_token_hash UNIQUE (token_hash)
);
